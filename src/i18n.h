// tr() but with the language passed explicitly — for UI that must show
// several languages at once (splash rotation) without disturbing the
// global LANGUAGE that the rest of the app reads.
inline std::string tr_in(const std::string& lang, const std::string& key) {
    if (lang == "zh") {
        auto it = lang_zh.params.find(key);
        return it != lang_zh.params.end() ? it->second : key;
    }
    if (lang == "en") {
        auto it = lang_en.params.find(key);
        return it != lang_en.params.end() ? it->second : key;
    }
    auto it = lang_ru.params.find(key);
    return it != lang_ru.params.end() ? it->second : key;
}

inline std::string tr(const std::string& key) {
    std::string lang = current_lang();
    if (lang == "zh") {
        auto it = lang_zh.params.find(key);
        return it != lang_zh.params.end() ? it->second : key;
    }
    if (lang == "en") {
        auto it = lang_en.params.find(key);
        return it != lang_en.params.end() ? it->second : key;
    }
    auto it = lang_ru.params.find(key);
    return it != lang_ru.params.end() ? it->second : key;
}
